export function getRegionsForMarket(market: Market): readonly RegionOption[] {
  return market === 'US' ? US_STATES_LIST : CANADIAN_PROVINCES_LIST;
}

export function getRegionLabel(market: Market): string {
  return market === 'US' ? 'State / Region' : 'Province / Territory';
}

export function getDefaultRegion(market: Market): string {
  return market === 'US' ? 'CA' : 'BC';
}

export function getRegionByCode(code?: string): RegionOption | undefined {
  if (!code) return undefined;
  const upper = code.toUpperCase();
  return (
    CANADIAN_PROVINCES_LIST.find((p) => p.code === upper) ||
    US_STATES_LIST.find((s) => s.code === upper)
  );
}

export function isValidRegionForMarket(code: string, market: Market): boolean {
  const upper = code.toUpperCase();
  const list = market === 'US' ? US_STATES_LIST : CANADIAN_PROVINCES_LIST;
  return list.some((item) => item.code === upper);
}
